export function seedIfEmpty(db) {
  const hasUsers = db.prepare('SELECT 1 FROM users LIMIT 1').get();
  if (hasUsers) return false;
  // Пароль случайный и нигде не сохраняется: в системный аккаунт нельзя войти.
  const ownerId = createUser(db, { username: 'agora', display_name: 'Команда Agora', password: randomToken(32), is_system: 1 });
  for (const d of DEMO) createAgent(db, ownerId, { version: '1.0', ...d });
  return true;
}
